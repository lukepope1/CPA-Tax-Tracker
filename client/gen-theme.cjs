// Generates client/src/theme.css. Run from client/: node gen-theme.cjs
const fs = require("fs");
const path = require("path");
const colors = require(path.resolve("node_modules/tailwindcss/colors"));

const rgb = (hex) => {
  const h = hex.replace("#", "");
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).join(" ");
};
const rgba = (hex, a) => `rgb(${rgb(hex)} / ${a})`;
const esc = (cls) => cls.replace(/([:/\[\]#.])/g, "\\$1");

// ---- grey scale: light (unchanged from before) and dark (inverted) ----
const grayLight = {
  50: "#f9fafb", 100: "#f3f4f6", 200: "#e5e7eb", 300: "#c4c9d1", 400: "#6b7280",
  500: "#5b6372", 600: "#454c59", 700: "#374151", 800: "#1f2937", 900: "#111827", 950: "#030712",
};
// Slightly teal-tinted so dark mode still feels like the brand, not plain grey.
const grayDark = {
  50: "#1b2828", 100: "#213030", 200: "#2c3b3b", 300: "#405150", 400: "#93a09f",
  500: "#a9b4b3", 600: "#bdc7c6", 700: "#d0d8d7", 800: "#e2e8e7", 900: "#eef2f2", 950: "#f7f9f9",
};

const out = [];
out.push(`/*
 * Light/dark theme. GENERATED by gen-theme.cjs — the colour-tint section is
 * derived from Tailwind's palette; edit the generator rather than this file.
 *
 * How dark mode works: the grey scale is CSS variables (tailwind.config.js), so
 * inverting them here flips every grey text/fill/border in the app at once. The
 * remaining light-only colours — white surfaces, brand-teal text, and the pale
 * colour tints used by status pills, chips and stat cards — get a dark
 * counterpart below, keyed to the exact classes the app uses. Solid colours
 * (buttons, the header, pipeline segments) already read well on dark and are
 * left alone.
 */`);

out.push(`:root {
${Object.entries(grayLight).map(([k, v]) => `  --gray-${k}: ${rgb(v)};`).join("\n")}
  --surface: #ffffff;
  --page: #f1f5f5;
}

html.dark {
  color-scheme: dark; /* native dark form controls, date pickers and scrollbars */
${Object.entries(grayDark).map(([k, v]) => `  --gray-${k}: ${rgb(v)};`).join("\n")}
  --surface: #152121;
  --page: #0c1515;
}`);

// Every selector in a comma list needs its own html.dark prefix: in CSS the
// prefix binds only to the selector it's written on, so "html.dark .a, .b"
// would apply .b in light mode too.
const D = (sel, body) =>
  out.push(`${sel.split(",").map((x) => `html.dark ${x.trim()}`).join(", ")} { ${body} }`);

out.push(`\n/* ---- surfaces ---- */`);
out.push(`.bg-page { background-color: var(--page); }`);
out.push(`html.dark body { color: rgb(var(--gray-800)); background-color: var(--page); }`);
D(`.bg-white:not(.keep-white)`, `background-color: var(--surface);`);
D(`.to-white`, `--tw-gradient-to: var(--surface) var(--tw-gradient-to-position);`);

out.push(`\n/* ---- brand teal: text lightens, tints become translucent ---- */`);
const brand = { 50: "#eef3f3", 300: "#88aaa9", 400: "#5d8482", 500: "#3e6664" };
D(`.text-brand-400`, `color: #8fb5b3;`);
D(`.text-brand-500`, `color: #9cc3c1;`);
D(`.text-brand-600, .text-brand-700`, `color: #a9cdca;`);
D(`.text-brand-800, .text-brand-900`, `color: #d3e6e4;`);
D(`.hover\\:text-brand-600:hover, .hover\\:text-brand-800:hover, .group:hover .group-hover\\:text-brand-700`, `color: #d3e6e4;`);
D(`.bg-brand-50`, `background-color: ${rgba(brand[500], 0.22)};`);
D(`.bg-brand-50\\/60`, `background-color: ${rgba(brand[500], 0.16)};`);
D(`.bg-brand-100`, `background-color: ${rgba(brand[500], 0.35)};`);
D(`.from-brand-50`, `--tw-gradient-from: ${rgba(brand[500], 0.22)} var(--tw-gradient-from-position);`);
D(`.border-brand-300, .border-y-brand-300, .border-r-brand-300`, `border-color: ${brand[500]};`);
D(`.ring-brand-200, .hover\\:ring-brand-200:hover`, `--tw-ring-color: ${rgba(brand[400], 0.6)};`);

// The current page in the header nav. A white pill reads as "selected" on the
// teal bar in light mode; in dark mode a translucent one does the same job.
// Placed after the brand-text rules above so its white text wins.
D(`.nav-active`, `background-color: rgb(255 255 255 / 0.16); color: #ffffff;`);

out.push(`\n/* ---- gold accent ---- */`);
D(`.from-accent-50`, `--tw-gradient-from: rgb(220 166 52 / 0.14) var(--tw-gradient-from-position);`);
D(`.text-accent-700`, `color: #e9bd57;`);

out.push(`\n/* ---- colour tints (status pills, chips, stat cards, alerts) ---- */`);
const families = ["red", "amber", "blue", "cyan", "green", "orange", "rose", "sky", "slate", "teal", "violet", "yellow"];
for (const f of families) {
  const c = colors[f];
  D(`.bg-${f}-50`, `background-color: ${rgba(c[500], 0.12)};`);
  D(`.bg-${f}-100`, `background-color: ${rgba(c[500], 0.2)};`);
  D(`.from-${f}-50`, `--tw-gradient-from: ${rgba(c[500], 0.15)} var(--tw-gradient-from-position);`);
  D(`.text-${f}-600, .text-${f}-700`, `color: ${c[400]};`);
  D(`.text-${f}-800, .text-${f}-900`, `color: ${c[300]};`);
  D(`.border-${f}-200`, `border-color: ${rgba(c[400], 0.35)};`);
  D(`.ring-${f}-300`, `--tw-ring-color: ${rgba(c[400], 0.45)};`);
}
D(`.hover\\:text-red-600:hover`, `color: ${colors.red[400]};`);

out.push(`\n/* ---- hand-written pieces in index.css ---- */`);
D(`thead tr`, `background-color: #1c2c2b;`);
D(`thead th`, `color: #b8d3d1;`);
D(`thead tr.border-b`, `border-bottom-color: #2f4a48;`);
D(`tbody tr:nth-child(even)`, `background-color: rgb(255 255 255 / 0.025);`);
D(`.overflow-x-auto::-webkit-scrollbar-thumb, .overflow-y-auto::-webkit-scrollbar-thumb`, `background: #3a4a49;`);
D(`input:focus-visible, select:focus-visible, textarea:focus-visible`, `border-color: #5d8482; box-shadow: 0 0 0 3px rgb(93 132 130 / 0.35);`);
D(`.rte a, .note-body a`, `color: #8ab4ff;`);
// Rich-text notes carry inline colours. The editor's "Default" text colour is a
// dark grey that would vanish on a dark card, and highlighted runs keep their
// bright yellow fill, so their text must stay dark to be readable.
D(`.note-body [style*="color: rgb(31, 41, 55)"], .rte [style*="color: rgb(31, 41, 55)"]`, `color: inherit !important;`);
D(`.note-body [style*="background-color"], .rte [style*="background-color"]`, `color: #111827 !important;`);

out.push(`\n/* ---- charts (recharts draws with inline attributes) ---- */`);
D(`.recharts-cartesian-grid line`, `stroke: #2c3b3b;`);
D(`.recharts-cartesian-axis-tick-value, .recharts-legend-item-text`, `fill: #a9b4b3; color: #a9b4b3 !important;`);
D(`.recharts-cartesian-axis-line`, `stroke: #2c3b3b;`);
D(`.recharts-default-tooltip`, `background-color: var(--surface) !important; border-color: #2f4a48 !important; color: #e2e8e7;`);
D(`.recharts-tooltip-label`, `color: #d3e6e4 !important;`);
D(`.recharts-tooltip-cursor`, `fill: rgb(255 255 255 / 0.05);`);
D(`.recharts-pie-sector path`, `stroke: var(--surface);`);

fs.writeFileSync("src/theme.css", out.join("\n") + "\n");
console.log("wrote src/theme.css:", out.length, "blocks");
